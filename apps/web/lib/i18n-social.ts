/** What the call layer on every page needs, so the layout sends only these to the browser. */
const callKeys = [
  "callFriend",
  "voiceCall",
  "callingYou",
  "acceptCall",
  "declineCall",
  "calling",
  "callConnecting",
  "callEnded",
  "callDeclined",
  "callNoAnswer",
  "callElsewhere",
  "callFailed",
  "endCall",
  "peerMuted",
  "micOn",
  "micOff",
  "micDenied",
] as const;
export type CallStrings = Pick<typeof socialEn, (typeof callKeys)[number]>;
export const callStrings = (texts: typeof socialEn): CallStrings =>
  Object.fromEntries(callKeys.map((key) => [key, texts[key]])) as CallStrings;
