export type Strings = typeof en &
  typeof socialEn &
  typeof feedEn &
  typeof shareEn &
  typeof notifyEn &
  typeof themesEn &
  typeof compatEn &
  typeof discoverEn &
  typeof familyEn &
  typeof storageEn;
/** What client components get: the same texts (kept as its own name for them). */
export type UiStrings = Strings;
export const ui = (texts: Strings): UiStrings => texts;

/** The language chosen with the switcher (the lang cookie); English until one is chosen. */
export async function language(): Promise<Language> {
  return (await cookies()).get(languageCookie)?.value === "tr" ? "tr" : "en";
}

/** The texts in the chosen language. */
export async function strings(): Promise<Strings> {
  return (await language()) === "tr"
    ? {
        ...tr,
        ...socialTr,
        ...feedTr,
        ...shareTr,
        ...notifyTr,
        ...themesTr,
        ...compatTr,
        ...discoverTr,
        ...familyTr,
        ...storageTr,
      }
    : {
        ...en,
        ...socialEn,
        ...feedEn,
        ...shareEn,
        ...notifyEn,
        ...themesEn,
        ...compatEn,
        ...discoverEn,
        ...familyEn,
        ...storageEn,
      };
}
