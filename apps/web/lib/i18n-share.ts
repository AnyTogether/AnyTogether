/** What the invite card on every page needs. */
const inviteKeys = ["shareInvitedYou", "shareWatch", "shareTitle"] as const;
export type ShareInviteStrings = Pick<typeof shareEn, (typeof inviteKeys)[number]> & { decline: string };
export const shareInviteStrings = (texts: typeof shareEn & { decline: string }): ShareInviteStrings => ({
  ...(Object.fromEntries(inviteKeys.map((key) => [key, texts[key]])) as Pick<
    typeof shareEn,
    (typeof inviteKeys)[number]
  >),
  decline: texts.decline,
});
